"""File downloaded art into a project's images/ folder under the right names.

Usage:
    picturebook import <project-dir> [source-dir] [options]

Options:
    --map LIST     Commit a mapping, e.g. "cover=abc.png,1=IMG_2.png,4=x.jpg".
    --by-order     Map the files not named for a page to the pages in order,
                   oldest file first.
    --resize       Resize to the print target instead of keeping the original.
    --color        File colour art, in images/color/, instead of line art.
    --dry-run      Say what would happen. Change nothing.

With no mapping, this scans and reports. It writes a contact sheet to
`images/_contact-sheet.html` and prints a proposed `--map` line you can edit
and pass straight back. Nothing moves until you commit a mapping, so a wrong
guess costs nothing.

The source folder defaults to `images/_incoming`, and also picks up any loose
file sitting in `images/` that is not already named for a page. That clears
the hand-downloaded files with service filenames such as
`u8476676792_Childrens_picture_book_..._3.png`.

A file generated by `picturebook generate` is named for its page already, as
`page-04.2.png`. The proposed `--map` line picks the newest such file for its
page, but it is still only a proposal. `picturebook pick` is the easier way
to choose between variants.

Colour art lives apart from the line art, in `images/color/` with its own
`_incoming/`, so filing one never touches the other. Pass `--color` for it.

Nothing is deleted and nothing is silently overwritten. A file already at the
target name moves to `images/_replaced/` with a timestamp first.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

from .bookdata import back_up, images_dir, load_book, parse_ratio

SUFFIXES = {".png", ".jpg", ".jpeg", ".webp"}
DPI = 300
AR_TOLERANCE = 0.02
# page-04.png, page-04.2.png, cover.png, cover.1.png
NAMED = re.compile(r"^(cover|page-(\d+))(\.\d+)?$", re.IGNORECASE)


def target_size(page: dict) -> tuple[int, int]:
    """The print pixel size for this book at 300 DPI.

    When `page.art_aspect` is set, the art is not the shape of the page. An
    activity book prints a square whatever the paper is, so the target comes
    from that ratio and `page.art_px`, the long side in pixels. Without it,
    every square image would be reported as the wrong shape and too small.
    """
    ratio = parse_ratio(str(page.get("art_aspect", "")).strip())
    if ratio:
        w_ratio, h_ratio = ratio
        long_side = int(page.get("art_px", 2048))
        if w_ratio >= h_ratio:
            return long_side, round(long_side * h_ratio / w_ratio)
        return round(long_side * w_ratio / h_ratio), long_side
    width = float(page.get("width_in", 8.0))
    height = float(page.get("height_in", 10.6667))
    return round(width * DPI), round(height * DPI)


def wanted(data: dict) -> dict[str, str]:
    """Page key to target filename, e.g. {"cover": "cover.png", "4": "page-04.png"}.

    The cover comes first, then the pages in book order.
    """
    out: dict[str, str] = {}
    cover = data.get("cover") or {}
    if cover.get("image"):
        out["cover"] = cover["image"]
    for page in data.get("pages", []):
        if page.get("image"):
            out[str(page.get("n"))] = page["image"]
    return out


def page_of(path: Path) -> str:
    """The page a generated filename claims, or "" if it claims none."""
    match = NAMED.match(path.stem)
    if not match:
        return ""
    if match.group(1).lower() == "cover":
        return "cover"
    return str(int(match.group(2)))


def sources(images: Path) -> list[Path]:
    """Every candidate file: _incoming, plus loose files in the images folder."""
    found: list[Path] = []
    incoming = images / "_incoming"
    if incoming.is_dir():
        found += [p for p in incoming.iterdir() if p.suffix.lower() in SUFFIXES]
    for path in images.iterdir():
        if path.suffix.lower() not in SUFFIXES:
            continue
        if NAMED.match(path.stem) and "." not in path.stem:
            continue  # already filed as page-04.png or cover.png
        found.append(path)
    return sorted(found, key=lambda p: p.stat().st_mtime)


def describe(path: Path, want_w: int, want_h: int) -> tuple[str, str]:
    """A one-line size report, and a warning if the shape or size is off."""
    try:
        with Image.open(path) as img:
            w, h = img.size
    except OSError as err:
        return "unreadable", f"cannot open ({err})"
    note = ""
    if want_h and abs((w / h) - (want_w / want_h)) > AR_TOLERANCE:
        note = f"shape is {w / h:.3f}, book wants {want_w / want_h:.3f}"
    elif w < want_w or h < want_h:
        note = f"smaller than the {want_w}x{want_h} print target"
    return f"{w}x{h}", note


def contact_sheet(project: Path, images: Path, files: list[Path],
                  report: dict[Path, tuple[str, str]]) -> Path:
    """An HTML page of every unfiled image, so you can see what you have."""
    rows = []
    for i, path in enumerate(files, 1):
        size, note = report[path]
        src = path.resolve().as_uri()
        warn = f'<p class="warn">{note}</p>' if note else ""
        rows.append(
            f'<figure><img src="{src}" alt=""><figcaption>'
            f'<b>{i}</b> {path.name}<br><span>{size}</span>{warn}'
            f"</figcaption></figure>"
        )
    html = f"""<!doctype html>
<meta charset="utf-8"><title>{project.name} — unfiled images</title>
<style>
 body {{ font: 14px/1.4 -apple-system, sans-serif; margin: 2rem; background: #fbfaf7; }}
 main {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(220px, 1fr)); gap: 1.5rem; }}
 figure {{ margin: 0; }}
 img {{ width: 100%; border: 1px solid #ddd; background: #fff; }}
 figcaption {{ font-size: 12px; word-break: break-all; margin-top: .4rem; }}
 span {{ color: #777; }}
 .warn {{ color: #a4442a; margin: .2rem 0 0; }}
</style>
<h1>{project.name} — {len(files)} unfiled image(s)</h1>
<main>{"".join(rows)}</main>
"""
    path = images / "_contact-sheet.html"
    path.write_text(html, encoding="utf-8")
    return path


def parse_map(value: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for part in value.split(","):
        part = part.strip()
        if not part:
            continue
        if "=" not in part:
            sys.exit(f"error: --map needs page=filename, got {part!r}")
        page, name = part.split("=", 1)
        out[page.strip()] = name.strip()
    return out


def flatten(img: Image.Image) -> Image.Image:
    """RGB, with any transparency composited onto white (not black)."""
    if img.mode == "P" and "transparency" in img.info:
        img = img.convert("RGBA")
    if img.mode in ("RGBA", "LA"):
        img = img.convert("RGBA")
        background = Image.new("RGBA", img.size, (255, 255, 255, 255))
        return Image.alpha_composite(background, img).convert("RGB")
    return img.convert("RGB")


def place(source: Path, target: Path, size: tuple[int, int] | None, dry: bool) -> str:
    """Write source to target as PNG, keeping whatever was already there."""
    if dry:
        return f"would write {target.name} from {source.name}"
    if target.exists():
        back_up(target)
    with Image.open(source) as opened:
        img = flatten(ImageOps.exif_transpose(opened))
        if size:
            # Crop to the target shape from the centre, then scale, so a picture
            # of another shape is cut rather than stretched.
            img = ImageOps.fit(img, size, Image.LANCZOS)
        img.save(target, "PNG")
    return f"wrote {target.name} from {source.name}"


def propose(targets: dict[str, str], files: list[Path]) -> dict[str, Path]:
    """A guess at which file belongs to which page. Nothing is filed from it.

    A file named for its page, such as page-04.2.png, goes to that page, and
    the newest one wins. Files with other names fill the pages left over, in
    book order, oldest file first. `files` must be sorted oldest first.
    """
    guess: dict[str, Path] = {}
    loose: list[Path] = []
    for path in files:
        page = page_of(path)
        if page in targets:
            guess[page] = path  # a later, newer file replaces an earlier one
        else:
            loose.append(path)
    left = [page for page in targets if page not in guess]
    guess.update(zip(left, loose))
    return {page: guess[page] for page in targets if page in guess}


def by_order(targets: dict[str, str], files: list[Path]) -> dict[str, Path]:
    """The files not named for a page, mapped to the pages in book order."""
    loose = [path for path in files if page_of(path) not in targets]
    return dict(zip(targets, loose))


def run(project: Path, args: argparse.Namespace) -> None:
    data = load_book(project)
    want_w, want_h = target_size(data.get("page", {}))
    targets = wanted(data)
    images = images_dir(project, args.color)
    if not images.is_dir():
        print(f"  {project.name}: no {images.relative_to(project)} folder yet")
        return

    files = sources(images)
    if not files:
        print(f"  {project.name}: nothing to file")
        return

    report = {path: describe(path, want_w, want_h) for path in files}

    # Only a mapping or --by-order files anything. A plain run reports.
    mapping: dict[str, Path] = {}
    if args.map:
        by_name = {path.name: path for path in files}
        for page, name in parse_map(args.map).items():
            if page not in targets:
                sys.exit(f"error: {project.name} has no page {page!r}")
            if name not in by_name:
                sys.exit(f"error: no file named {name!r} in the source folders")
            mapping[page] = by_name[name]
    elif args.by_order:
        mapping = by_order(targets, files)

    print(f"\n=== {project.name} — {len(files)} unfiled, {len(mapping)} mapped ===")
    for path in files:
        size, note = report[path]
        flag = "  <-- " + note if note else ""
        print(f"  {path.name[:52]:<54} {size:<11}{flag}")

    if not mapping:
        sheet = contact_sheet(project, images, files, report)
        guess = ",".join(f"{page}={path.name}"
                         for page, path in propose(targets, files).items())
        print(f"\n  contact sheet: {sheet}")
        print("\n  nothing filed. Pass a mapping to commit, for example:")
        print(f"\n    --map \"{guess}\"\n")
        return

    size = (want_w, want_h) if args.resize else None
    for page in sorted(mapping, key=list(targets).index):
        print("  " + place(mapping[page], images / targets[page], size, args.dry_run))
    if args.dry_run:
        print("\n  dry run — nothing changed")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("project", type=Path)
    ap.add_argument("source", nargs="?", type=Path, default=None)
    ap.add_argument("--map", default="", help='e.g. "cover=a.png,1=b.png"')
    ap.add_argument("--by-order", action="store_true")
    ap.add_argument("--resize", action="store_true")
    ap.add_argument("--color", action="store_true", help="file colour art, in images/color/")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    project = args.project.expanduser().resolve()
    if args.source:
        source = args.source.expanduser().resolve()
        if not source.is_dir():
            sys.exit(f"error: source folder {args.source} does not exist or is not a folder")
        # Copy the files into _incoming, so the scan finds them there.
        incoming = images_dir(project, args.color) / "_incoming"
        incoming.mkdir(parents=True, exist_ok=True)
        for path in sorted(source.iterdir()):
            if path.suffix.lower() in SUFFIXES:
                target = incoming / path.name
                if not target.exists():
                    target.write_bytes(path.read_bytes())
    run(project, args)
