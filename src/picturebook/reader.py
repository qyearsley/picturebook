"""Build a single-file HTML reader from a book project's book-data.json.

Usage:
    picturebook reader [project-dir] [--out FILE] [--no-copy-images]
                            [--color] [--web]

The reader is one index.html with inline CSS and JS. It uses CSS scroll-snap,
so each page fills the screen and swipes cleanly on an iPad. Pinyin sits above
the Chinese characters in <ruby> tags, generated by pinyin.py.

By default the script copies images into build/images/, which makes build/ a
self-contained folder you can push to GitHub Pages.

`--color` reads the art from `images/color/` instead of the line art.
`--web` writes each image as a JPEG instead of copying the PNG, which cuts a
colour book's images from about 25 MB to about 4 MB.
"""

