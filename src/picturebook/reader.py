def render(data: dict, image_prefix: str, available: set[str], sandhi: bool = True) -> str:
    title = data.get("title", {})
    title_en = title.get("en", "")
    title_zh = title.get("zh", "")
    author = data.get("author") or ""
    overrides = data.get("pinyin_overrides") or {}

    def ruby(text: str) -> str:
        # The text is verse. Keep the author's line breaks instead of reflowing.
        return "<br>".join(ruby_html(line, overrides, sandhi) for line in text.split("\n"))

    def plain(text: str) -> str:
        return "<br>".join(html.escape(line) for line in text.split("\n"))

    parts: list[str] = []
    parts.append("<section class='page cover'>")
    cover_image = (data.get("cover") or {}).get("image")
    if cover_image and cover_image in available:
        parts.append(
            f"<img class='art' src='{image_prefix}{html.escape(cover_image)}' alt='' loading='eager'>"
        )
    if title_en:
        parts.append(f"<h1>{html.escape(title_en)}</h1>")
    if title_zh:
        parts.append(f"<h2 lang='zh-Hans'>{ruby(title_zh)}</h2>")
    if author:
        parts.append(f"<p class='byline'>{html.escape(author)}</p>")
    parts.append("<p class='hint'>Swipe or press &darr; to turn the page.</p>")
    parts.append("</section>")

    for page in data.get("pages", []):
        n = page.get("n", "")
        image = page.get("image") or ""
        parts.append("<section class='page'>")
        if image and image in available:
            parts.append(
                f"<img class='art' src='{image_prefix}{html.escape(image)}' "
                f"alt='Illustration for page {n}' loading='lazy' decoding='async'>"
            )
        elif image:
            parts.append(
                f"<div class='art-missing'><span>missing image</span>"
                f"<span>{html.escape(image)}</span></div>"
            )
        parts.append("<div class='text'>")
        if page.get("en"):
            parts.append(f"<p class='en'>{plain(page['en'])}</p>")
        if page.get("zh"):
            parts.append(f"<p class='zh' lang='zh-Hans'>{ruby(page['zh'])}</p>")
        parts.append("</div>")
        parts.append(f"<span class='pagenum'>{html.escape(str(n))}</span>")
        parts.append("</section>")

    doc_title = title_en or title_zh or "Picture book"
    both = " / ".join(t for t in (title_en, title_zh) if t)
    description = f"{both}: a picture book in English and Chinese, with pinyin."
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="theme-color" content="#fdfcf8" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#14171c" media="(prefers-color-scheme: dark)">
<title>{html.escape(doc_title)}</title>
<meta name="description" content="{html.escape(description)}">
<style>{CSS}</style>
</head>
<body>
<div id="controls">
  <button id="toggle-pinyin" type="button" aria-pressed="true">Pinyin</button>
  <button id="toggle-en" type="button" aria-pressed="true">English</button>
</div>
<main>
{chr(10).join(parts)}
</main>
<script>{JS}</script>
</body>
</html>
"""


def build(project: Path, out: Path | None, copy_images: bool, sandhi: bool = True,
          color: bool = False, web: bool = False) -> Path:
    data = load_book(project)
    art = images_dir(project, color)
    build_dir = project / "build"
    build_dir.mkdir(parents=True, exist_ok=True)
    # Each edition gets its own folder, so a colour build never replaces the
    # line build's images, and a JPEG build leaves no PNGs behind.
    out = out or build_dir / edition_dir(color, web) / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)

    wanted = [p["image"] for p in data.get("pages", []) if p.get("image")]
    cover_image = (data.get("cover") or {}).get("image")
    if cover_image:
        wanted.append(cover_image)
    available = {name for name in wanted if (art / name).exists()}

    if copy_images:
        target = out.parent / "images"
        target.mkdir(parents=True, exist_ok=True)
        written = set()
        for name in sorted(available):
            if web:
                with Image.open(art / name) as img:
                    img.convert("RGB").save(target / web_name(name), "JPEG",
                                            quality=WEB_JPEG_QUALITY, optimize=True)
                written.add(web_name(name))
            else:
                shutil.copy2(art / name, target / name)
                written.add(name)
        # A page whose art was removed, or an older build's format, would
        # otherwise linger beside the new files.
        for old in target.iterdir():
            if old.is_file() and old.name not in written:
                old.unlink()
        prefix = "images/"
        if web:
            # The parsed copy only: book-data.json keeps its PNG names.
            for entry in [data.get("cover") or {}] + data.get("pages", []):
                if entry.get("image") in available:
                    entry["image"] = web_name(entry["image"])
            available = {web_name(name) for name in available}
            wanted = [web_name(name) for name in wanted]
    else:
        prefix = f"{os.path.relpath(art, out.parent)}/"

    out.write_text(render(data, prefix, available, sandhi), encoding="utf-8")

    missing = [n for n in wanted if n not in available]
    if missing:
        print(f"  {len(missing)} image(s) missing, shown as placeholders: {', '.join(missing)}")
    return out


def edition_dir(color: bool, web: bool) -> str:
    """build/reader, build/reader-color, build/reader-color-web, ..."""
    return "-".join(["reader"] + (["color"] if color else []) + (["web"] if web else []))


def web_name(name: str) -> str:
    """page-01.png -> page-01.jpg"""
    return str(Path(name).with_suffix(".jpg"))


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Build an HTML reader with pinyin ruby text.")
    ap.add_argument("project", nargs="?", default=".", type=Path, help="project directory (default: cwd)")
    ap.add_argument("--out", type=Path, help="output HTML path (default: <project>/build/reader/index.html,"
                         " or reader-color, reader-web, reader-color-web)")
    ap.add_argument("--no-copy-images", action="store_true",
                    help="link to ../images instead of copying into build/")
    ap.add_argument("--no-sandhi", action="store_true",
                    help="skip the 一 and 不 tone changes and use dictionary tones")
    ap.add_argument("--color", action="store_true",
                    help="use the colour art in images/color/ instead of the line art")
    ap.add_argument("--web", action="store_true",
                    help="write the images as JPEG, for a smaller folder to put online")
    args = ap.parse_args(argv)
    if args.web and args.no_copy_images:
        ap.error("--web writes JPEG copies, so it cannot be used with --no-copy-images")

    out = build(args.project.expanduser().resolve(), args.out,
                not args.no_copy_images, not args.no_sandhi, args.color, args.web)
    print(f"  wrote {out}")
